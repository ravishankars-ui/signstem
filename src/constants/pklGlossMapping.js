/**
 * Resolves a token/gloss word to its corresponding .pkl / .json filename.
 * 
 * @param {string} token - e.g. "HELLO", "learn", "10014.pkl", "MOTION"
 * @returns {string | null} Filename (e.g. '10014.pkl') or null if not mapped
 */
export function getPklFileForGloss(token) {
  if (!token || typeof token !== 'string') return null;

  // Direct .pkl or .json filename request
  if (token.endsWith('.pkl')) return token;
  if (token.endsWith('.json')) return token.replace('.json', '.pkl');

  const key = token.toUpperCase().replace(/[^A-Z0-9_]/g, '').trim();
  if (PKL_GLOSS_MAPPING[key]) {
    return PKL_GLOSS_MAPPING[key];
  }

  // Fallback 1: Numeric ID directly (e.g. "10014" -> "10014.pkl")
  if (/^\d{4,5}$/.test(key)) {
    return `${key}.pkl`;
  }

  // Fallback 2: Substring matching for compound words
  const keys = Object.keys(PKL_GLOSS_MAPPING);
  const match = keys.find(k => k === key || (key.length >= 4 && (k.includes(key) || key.includes(k))));
  return match ? PKL_GLOSS_MAPPING[match] : null;
}

export default getPklFileForGloss;
